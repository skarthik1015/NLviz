"""Development set, database 1: TPC-H at scale 0.1 in the dev Postgres (database `tpch`).

Generated by DuckDB's tpch extension (deterministic), copied into Postgres with the column types
TPC-H specifies, primary and foreign keys declared (NLviz reads joins from them), and read access
for the app's read-only user.

    python eval/bench/datasets/load_tpch.py --password-file <postgres superuser pw> [--port 15432]
"""
from __future__ import annotations

import argparse
import io
from pathlib import Path

import duckdb
import psycopg2

TABLES = {
    "region": """r_regionkey integer PRIMARY KEY, r_name char(25) NOT NULL, r_comment varchar(152)""",
    "nation": """n_nationkey integer PRIMARY KEY, n_name char(25) NOT NULL,
                 n_regionkey integer NOT NULL REFERENCES region, n_comment varchar(152)""",
    "supplier": """s_suppkey integer PRIMARY KEY, s_name char(25) NOT NULL, s_address varchar(40) NOT NULL,
                   s_nationkey integer NOT NULL REFERENCES nation, s_phone char(15) NOT NULL,
                   s_acctbal numeric(15,2) NOT NULL, s_comment varchar(101) NOT NULL""",
    "customer": """c_custkey integer PRIMARY KEY, c_name varchar(25) NOT NULL, c_address varchar(40) NOT NULL,
                   c_nationkey integer NOT NULL REFERENCES nation, c_phone char(15) NOT NULL,
                   c_acctbal numeric(15,2) NOT NULL, c_mktsegment char(10) NOT NULL, c_comment varchar(117) NOT NULL""",
    "part": """p_partkey integer PRIMARY KEY, p_name varchar(55) NOT NULL, p_mfgr char(25) NOT NULL,
               p_brand char(10) NOT NULL, p_type varchar(25) NOT NULL, p_size integer NOT NULL,
               p_container char(10) NOT NULL, p_retailprice numeric(15,2) NOT NULL, p_comment varchar(23) NOT NULL""",
    "partsupp": """ps_partkey integer NOT NULL REFERENCES part, ps_suppkey integer NOT NULL REFERENCES supplier,
                   ps_availqty integer NOT NULL, ps_supplycost numeric(15,2) NOT NULL, ps_comment varchar(199) NOT NULL,
                   PRIMARY KEY (ps_partkey, ps_suppkey)""",
    "orders": """o_orderkey integer PRIMARY KEY, o_custkey integer NOT NULL REFERENCES customer,
                 o_orderstatus char(1) NOT NULL, o_totalprice numeric(15,2) NOT NULL, o_orderdate date NOT NULL,
                 o_orderpriority char(15) NOT NULL, o_clerk char(15) NOT NULL, o_shippriority integer NOT NULL,
                 o_comment varchar(79) NOT NULL""",
    "lineitem": """l_orderkey integer NOT NULL REFERENCES orders, l_partkey integer NOT NULL REFERENCES part,
                   l_suppkey integer NOT NULL REFERENCES supplier, l_linenumber integer NOT NULL,
                   l_quantity numeric(15,2) NOT NULL, l_extendedprice numeric(15,2) NOT NULL,
                   l_discount numeric(15,2) NOT NULL, l_tax numeric(15,2) NOT NULL, l_returnflag char(1) NOT NULL,
                   l_linestatus char(1) NOT NULL, l_shipdate date NOT NULL, l_commitdate date NOT NULL,
                   l_receiptdate date NOT NULL, l_shipinstruct char(25) NOT NULL, l_shipmode char(10) NOT NULL,
                   l_comment varchar(44) NOT NULL, PRIMARY KEY (l_orderkey, l_linenumber)""",
}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--password-file", required=True)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=15432)
    parser.add_argument("--scale", type=float, default=0.1)
    args = parser.parse_args()
    password = Path(args.password_file).read_text().strip()

    duck = duckdb.connect()
    duck.execute("INSTALL tpch; LOAD tpch")
    duck.execute(f"CALL dbgen(sf={args.scale})")

    admin = psycopg2.connect(host=args.host, port=args.port, user="postgres", password=password, dbname="postgres")
    admin.autocommit = True
    with admin.cursor() as cur:
        cur.execute("DROP DATABASE IF EXISTS tpch WITH (FORCE)")
        cur.execute("CREATE DATABASE tpch")
    admin.close()

    conn = psycopg2.connect(host=args.host, port=args.port, user="postgres", password=password, dbname="tpch")
    with conn, conn.cursor() as cur:
        for table, columns in TABLES.items():  # parents first, for the foreign keys
            cur.execute(f"CREATE TABLE {table} ({columns})")
            buffer = io.StringIO()
            frame = duck.execute(f"SELECT * FROM {table}").df()
            frame.to_csv(buffer, index=False, header=False)
            buffer.seek(0)
            cur.copy_expert(f"COPY {table} FROM STDIN WITH (FORMAT csv)", buffer)
            print(f"{table}: {len(frame)} rows")
        cur.execute("GRANT CONNECT ON DATABASE tpch TO nlviz_ro")
        cur.execute("GRANT USAGE ON SCHEMA public TO nlviz_ro")
        cur.execute("GRANT SELECT ON ALL TABLES IN SCHEMA public TO nlviz_ro")
        cur.execute("ANALYZE")
    conn.close()


if __name__ == "__main__":
    main()
